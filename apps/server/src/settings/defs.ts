/** Live hooks that read several keys at once (installed once after the registry exists). */
export function wireSettings(reg: SettingsRegistry): void {
  setVoiceSettingsProvider(() => ({
    monthlyMinutes: reg.get<number>('voice.monthlyMinutes'),
    maxConcurrent: reg.get<number>('voice.maxConcurrent'),
    maxPerLobby: reg.get<number>('voice.maxPerLobby'),
    maxPerIp: reg.get<number>('voice.maxPerIp'),
    idleMs: reg.get<number>('voice.idleMinutes') * 60_000,
    waitingMaxMs: reg.get<number>('voice.waitingMaxMinutes') * 60_000,
    announceMaxMs: reg.get<number>('voice.announceMaxMinutes') * 60_000,
    reconcileMs: reg.get<number>('voice.reconcileSeconds') * 1000,
    alertWarnPct: reg.get<number>('voice.alertWarnPct'),
    alertCriticalPct: reg.get<number>('voice.alertCriticalPct'),
    alertWebhook: reg.get<string>('voice.alertWebhook') || null,
  }));
}

export const DEFAULT_MAINTENANCE_MESSAGE = 'The town is closed for maintenance. Please come back a little later.';

const HOST_DANGEROUS = new Set<keyof HostLimits>(['socketFrameBurst', 'socketFramesPerSec', 'socketByteBurst', 'socketBytesPerSec', 'httpMaxConnections', 'httpHeadersTimeoutMs', 'httpRequestTimeoutMs']);
const HOST_GROUP = (k: keyof HostLimits): 'signups' | 'abuse' => (k === 'signupPerHour' ? 'signups' : 'abuse');
const HOST_UNIT: Record<string, string> = { count: '', per_sec: '/s', bytes: 'bytes', bytes_per_sec: 'bytes/s', per_hour: '/hour', ms: 'ms', per_min: '/min' };
const HOST_HELP: Partial<Record<keyof HostLimits, string>> = {
  socketFrameBurst: 'Messages one game connection may send in a burst before it is closed (pre-decode budget).',
  socketFramesPerSec: 'Sustained messages per second per game connection.',
  socketByteBurst: 'Bytes one game connection may send in a burst.',
  socketBytesPerSec: 'Sustained bytes per second per game connection.',
  sseMaxPerAccount: 'Open lobby-list streams per account (extra tabs fall back to a slower refresh).',
  sseMaxPerIp: 'Open lobby-list streams per network.',
  sseMaxTotal: 'Open lobby-list streams on the whole server.',
  signupPerHour: 'New accounts per hour on the whole server. 0 = unlimited, -1 = the server default (HOST_SIGNUP_PER_HOUR, else 100).',
  recordListMax: 'Entries kept per list inside one saved game record.',
  recordMaxBytes: 'Largest game record that is saved.',
  httpHeadersTimeoutMs: 'Time a client has to send its request headers (slow-loris protection). New connections only.',
  httpRequestTimeoutMs: 'Time a client has to send a whole request. New connections only.',
  httpMaxConnections: 'Open HTTP/WebSocket connections on the whole server.',
  uncaughtMaxBurst: 'Unexpected errors tolerated within the window before the server restarts itself cleanly.',
  uncaughtWindowMs: 'Window for the unexpected-error count.',
  consoleLinesPerMin: 'console warnings/errors written to the log per minute (protects the journal).',
};

const httpsUrl = (v: SettingValue) => (v === '' || (typeof v === 'string' && /^https:\/\/[^\s]+$/.test(v)) ? null : 'must be an https:// URL or empty');


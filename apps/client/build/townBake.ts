// v3.3 perf (v33-bake). BUILD-TIME TOWN BAKE, docs/perf-v3/bake.md.
//
// The procedural town costs ~2-4 s of main-thread JS at every join (docs/perf-v3/fullstack.md §2); 46 % of it is
// `createTree` (src/world/trees.js): the jagged crown cores, the crease test and the Poisson leaf scatter, all fbm3
// noise per vertex / per sample, called ~110 times by the foliage piece (tree templates, rim forest) and by the
// cottages' leaf clumps (house-1 / -4 / -11). createTree is a pure function of its options + the build camera's texel
// size, so its OUTPUT DATA is baked at build time (scripts/v3/bake-town.mjs runs the vendor headless in Node) and the
// game replays it: the patched createTree looks the call up in the bake and, on a hit, assembles the very same
// THREE.Group (same materials, same meshes, same sorter) from the baked arrays instead of generating them.
//
//   PATCH (applied to v3/pixel3d/src/world/trees.js by build/pixel3dImports.ts, in Vite AND in the Node bake):
//     createTree(engine, opts) -> globalThis.__ctTreeBake?.get(engine, opts) ? __ctAssembleTree(...) : raw createTree,
//     and a recording hook (`put`) the bake script uses to capture each live result (+ its unsorted leaf list).
//   DRIFT: the patch pins a sha256 of the vendor createTree source (the assembly below duplicates its tail). A vendor
//     re-publish that touches createTree FAILS THE BUILD here; re-verify __ctAssembleTree against it, then re-pin.
//     The bake itself is regenerated by every client build (vite plugin below) and carries the vendor hash of every
//     file the town build loaded; the client refuses a bake whose hash differs from the one compiled into it.
//   KEYS: the stable JSON of the call's options (minus position / add, which only the assembly reads) + the build
//     camera's texelWorld (leaf spacing is in screen texels). A miss (another window height, a new tree) generates live.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import path from 'node:path';

/** sha256 (hex, first 16) of the vendor `export function createTree … \n}\n` source the assembly was checked against. */
export const CREATE_TREE_PIN = '094fc72999fc155c';

/** The vendor createTree function source (from its export line to the first column-0 closing brace). */
export function createTreeSource(code: string): string | null {
  const head = 'export function createTree(engine, opts = {}) {';
  const i = code.indexOf(head);
  if (i < 0 || code.indexOf(head, i + 1) >= 0) return null;
  const j = code.indexOf('\n}\n', i);
  return j < 0 ? null : code.slice(i, j + 3);
}

export const sha16 = (s: string): string => createHash('sha256').update(s).digest('hex').slice(0, 16);

// The code injected into trees.js. Plain JS (vendor module scope: THREE, CELL, TREE_PALETTES, trunkMaterial,
// coreMaterial, leafMaterial, registerSorter, camForward are trees.js locals).
const WRAPPER = `export function createTree(engine, opts = {}) {
  const __b = globalThis.__ctTreeBake;
  const __d = __b ? __b.get(engine, opts) : null;
  if (__d) return __ctAssembleTree(engine, opts, __d);
  const g = __ctCreateTreeRaw(engine, opts);
  if (__b && __b.put) __b.put(engine, opts, g);
  delete g.userData.__ctLeaves;
  return g;
}
function __ctCreateTreeRaw(engine, opts = {}) {`;

const ASSEMBLY = `
// (clocktower town: build/townBake.ts) createTree from baked data: the tail of createTree (group, trunk, core, leaf
// instances, sorter, rim, userData) with the generated geometry / leaf list taken from the bake. Keep in step with
// createTree (the build pins its source hash).
function __ctAssembleTree(engine, opts, d) {
  const { position = new THREE.Vector3(), seed = 1, kind = 'round', outline = false, add = true, renderOrder } = opts;
  const pal = { ...(TREE_PALETTES[kind] ?? TREE_PALETTES.round), ...(opts.palette ?? {}) };
  const group = new THREE.Group();
  group.name = \`tree-\${kind}-\${seed}\`;
  group.position.copy(position);
  if (d.trunk) {
    const trunk = new THREE.Mesh(d.trunk(), trunkMaterial(engine, pal.trunk));
    trunk.castShadow = true; trunk.receiveShadow = true;
    trunk.name = 'trunk';
    group.add(trunk);
  }
  const core = new THREE.Mesh(d.core(), coreMaterial(engine, pal));
  core.castShadow = true; core.receiveShadow = true; core.name = 'core';
  group.add(core);
  const L = d.leaves(), N = L.n;
  const cHi = new THREE.Color(pal.hi), cMid = new THREE.Color(pal.mid), cSh = new THREE.Color(pal.sh), cTip = new THREE.Color(pal.tip), cCore = new THREE.Color(pal.core);
  const geo = new THREE.InstancedBufferGeometry();
  const quad = new THREE.PlaneGeometry(CELL, CELL);
  geo.index = quad.index;
  geo.setAttribute('position', quad.attributes.position);
  geo.setAttribute('uv', quad.attributes.uv);
  geo.setAttribute('normal', quad.attributes.normal);
  const A = {
    aBase: new Float32Array(N * 3), aN: new Float32Array(N * 3), aVar: new Float32Array(N * 4), aRad: new Float32Array(N),
    color: new Float32Array(N * 3), toneHi: new Float32Array(N * 3), toneSh: new Float32Array(N * 3), aCore: new Float32Array(N * 3),
    aTip: new Float32Array(N * 3), aOcc: new Float32Array(N),
  };
  const size = { aBase: 3, aN: 3, aVar: 4, aRad: 1, color: 3, toneHi: 3, toneSh: 3, aCore: 3, aTip: 3, aOcc: 1 };
  for (const k in A) geo.setAttribute(k, new THREE.InstancedBufferAttribute(A[k], size[k]));
  geo.instanceCount = N;
  const crownC = new THREE.Vector3(d.sphere[0], d.sphere[1], d.sphere[2]), crownR = d.sphere[3];
  geo.boundingSphere = new THREE.Sphere(crownC, crownR);
  geo.boundingBox = new THREE.Box3().setFromCenterAndSize(crownC, new THREE.Vector3(1, 1, 1).multiplyScalar(crownR * 2));
  const B = L.base, NN = L.n3, VV = L.v4, RR = L.rad, OO = L.occ;
  const fill = (order) => {
    for (let i = 0; i < order.length; i++) {
      const l = order[i];
      A.aBase.set([B[l * 3], B[l * 3 + 1], B[l * 3 + 2]], i * 3);
      A.aN.set([NN[l * 3], NN[l * 3 + 1], NN[l * 3 + 2]], i * 3);
      A.aVar.set([VV[l * 4], VV[l * 4 + 1], VV[l * 4 + 2], VV[l * 4 + 3]], i * 4);
      A.aRad[i] = RR[l];
      A.aOcc[i] = OO[l];
      A.color.set([cMid.r, cMid.g, cMid.b], i * 3);
      A.toneHi.set([cHi.r, cHi.g, cHi.b], i * 3);
      A.aTip.set([cTip.r, cTip.g, cTip.b], i * 3);
      A.toneSh.set([cSh.r, cSh.g, cSh.b], i * 3);
      A.aCore.set([cCore.r, cCore.g, cCore.b], i * 3);
    }
    for (const k in A) geo.attributes[k].needsUpdate = true;
  };
  const sortFor = (fwd) => {
    const dd = new Array(N);
    for (let i = 0; i < N; i++) dd[i] = (B[i * 3] * fwd.x + B[i * 3 + 1] * fwd.y + B[i * 3 + 2] * fwd.z) - VV[i * 4 + 3] * 0.1;
    const idx = Array.from({ length: N }, (_, i) => i).sort((a, b) => dd[b] - dd[a]);
    fill(idx);
  };
  sortFor(camForward(engine.camera));
  registerSorter(engine, sortFor);
  const order = renderOrder ?? (kind === 'bush' ? 0 : 1);
  if (outline) {
    const rim = new THREE.Mesh(geo, leafMaterial(engine, true, pal.rim ?? 0.72));
    rim.castShadow = false; rim.receiveShadow = true; rim.renderOrder = order; rim.name = 'leaf-rim';
    group.add(rim);
  }
  const leafMesh = new THREE.Mesh(geo, leafMaterial(engine, false));
  leafMesh.castShadow = false; leafMesh.receiveShadow = true; leafMesh.renderOrder = order; leafMesh.name = 'leaves';
  group.add(leafMesh);
  group.userData.tree = d.tree();
  if (add) engine.scene.add(group);
  return group;
}
`;

/** The unsorted leaf list is exposed to the recording hook only (scripts/v3/bake-town.mjs). */
const USERDATA_LINE = '  group.userData.tree = { kind, seed, crowns: shapes.map((s) => ({ c: s.c.clone(), r: s.R })), leaves: N, height: layout.h };';

/** Patch src/world/trees.js (null = a snippet is missing or createTree drifted from the pinned source). */
export function patchTrees(code: string): string | null {
  const src = createTreeSource(code);
  if (!src || sha16(src) !== CREATE_TREE_PIN) return null;
  const head = 'export function createTree(engine, opts = {}) {';
  if (!src.includes(USERDATA_LINE)) return null;
  const body = src.replace(head, WRAPPER).replace(USERDATA_LINE, `${USERDATA_LINE}\n  if (globalThis.__ctTreeBake && globalThis.__ctTreeBake.put) group.userData.__ctLeaves = leaves;`);
  return code.replace(src, body) + ASSEMBLY;
}

/**
 * The client's tree-cache key (vite define __CT_VENDOR_HASH__): every file of v3/pixel3d/src, the patch + the format +
 * the client cache module, and the three version. Any change = a new hash = every cached record is ignored and purged.
 */
export function vendorTreeHash(repoRoot: string, threeVersion: string): string {
  const files: string[] = [];
  const walk = (d: string) => {
    for (const n of readdirSync(d).sort()) {
      const p = path.join(d, n);
      if (statSync(p).isDirectory()) walk(p);
      else if (n.endsWith('.js') || n.endsWith('.json')) files.push(p);
    }
  };
  walk(path.join(repoRoot, 'v3/pixel3d/src'));
  for (const f of ['apps/client/build/townBake.ts', 'apps/client/src/game3d/vendor/bakeFormat.ts', 'apps/client/src/game3d/vendor/townBake.ts']) files.push(path.join(repoRoot, f));
  const h = createHash('sha256');
  for (const f of files) h.update(`${path.relative(repoRoot, f).split(path.sep).join('/')}\n`).update(readFileSync(f)).update('\n');
  return h.update(`three@${threeVersion}\n`).digest('hex').slice(0, 24);
}


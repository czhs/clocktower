import { useState } from 'preact/hooks';
import { CHARACTER_PRESETS, type CharacterPreset } from '@ct/assets';
import {
  ACCESSORIES,
  GHOST_STYLES,
  HAIR_COLORS,
  HAIR_STYLES,
  OUTFIT_PALETTES,
  OUTFITS,
  SKIN_TONES,
  type Cosmetics,
} from '@ct/protocol';
import { CosmeticPreview } from '../../game/CosmeticPreview';

// Character picker: a gallery of premade villagers (portrait + name + blurb) with a live animated
// preview. Layered customization sits behind "Advanced customization". Picking a villager sets
// `preset`; editing any layer sets `preset: null` (the layered fields are kept either way, so
// switching back and forth is lossless).

// Portraits generated by @ct/assets (generated/presets/<id>-portrait.png). Missing ones fall back
// to a small sprite render.
const PORTRAITS: Record<string, string> = Object.fromEntries(
  Object.entries(
    import.meta.glob('../../../../../packages/assets/generated/presets/*-portrait.png', { eager: true, query: '?url', import: 'default' }) as Record<
      string,
      string
    >,
  ).map(([path, url]) => [path.split('/').pop()!.replace(/-portrait\.png$/, ''), url]),
);

type LayerKey = Exclude<keyof Cosmetics, 'preset'>;
const FIELDS: { key: LayerKey; label: string; options: readonly string[] }[] = [
  { key: 'skin', label: 'Skin', options: SKIN_TONES },
  { key: 'hair', label: 'Hair', options: HAIR_STYLES },
  { key: 'hairColor', label: 'Hair colour', options: HAIR_COLORS },
  { key: 'outfit', label: 'Outfit', options: OUTFITS },
  { key: 'palette', label: 'Palette', options: OUTFIT_PALETTES },
  { key: 'accessory', label: 'Accessory', options: ACCESSORIES },
  { key: 'ghost', label: 'Ghost', options: GHOST_STYLES },
];

const cap = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);

export const presetOf = (c: Cosmetics): CharacterPreset | undefined => (c.preset ? CHARACTER_PRESETS.find((p) => p.id === c.preset) : undefined);

/** A random premade villager (new accounts start with one so nobody has to customise first). */
export function randomPreset(): string | null {
  if (!CHARACTER_PRESETS.length) return null;
  return CHARACTER_PRESETS[Math.floor(Math.random() * CHARACTER_PRESETS.length)]!.id;
}

export function CosmeticEditor({
  value,
  onChange,
  disabled,
  compact,
  simple,
}: {
  value: Cosmetics;
  onChange: (c: Cosmetics) => void;
  disabled?: boolean;
  /** Smaller gallery (waiting-room sheet). */
  compact?: boolean;
  /** Gallery only (no "Advanced customization"), e.g. during sign-up. */
  simple?: boolean;
}) {
  const preset = presetOf(value);
  const [advanced, setAdvanced] = useState(!preset && CHARACTER_PRESETS.length === 0);
  return (
    <div class={`ct-cosmetics${compact ? ' ct-cosmetics-compact' : ''}`}>
      <div class="ct-cosmetic-preview">
        <div class="ct-cosmetic-stage">
          <CosmeticPreview cosmetics={value} scale={compact ? 3 : 4} />
          <CosmeticPreview cosmetics={value} ghost scale={compact ? 2 : 3} animate={false} />
        </div>
        <div class="ct-cosmetic-name">{preset ? preset.name : 'Custom villager'}</div>
        <div class="ct-cosmetic-blurb muted">
          {preset ? preset.blurb : `${cap(value.outfit)}${value.accessory !== 'none' ? ` · ${value.accessory}` : ''} · ghost: ${value.ghost}`}
        </div>
      </div>

      {CHARACTER_PRESETS.length > 0 && (
        <div class="ct-presets" role="radiogroup" aria-label="Choose a villager">
          {CHARACTER_PRESETS.map((p) => {
            const on = value.preset === p.id;
            return (
              <button
                key={p.id}
                type="button"
                role="radio"
                aria-checked={on}
                aria-label={p.name}
                title={`${p.name} — ${p.blurb}`}
                class={`ct-preset${on ? ' on' : ''}`}
                disabled={disabled}
                onClick={() => onChange({ ...value, preset: p.id })}
              >
                {PORTRAITS[p.id] ? (
                  <img src={PORTRAITS[p.id]} alt="" width={48} height={48} draggable={false} />
                ) : (
                  <CosmeticPreview cosmetics={{ ...value, preset: p.id }} scale={2} animate={false} />
                )}
                <span class="ct-preset-name">{p.name}</span>
              </button>
            );
          })}
        </div>
      )}

      {!simple && (
      <details class="ct-advanced" open={advanced} onToggle={(e) => setAdvanced((e.currentTarget as HTMLDetailsElement).open)}>
        <summary>Advanced customization</summary>
        <div class="ct-cosmetics-fields">
          {FIELDS.map((f) => (
            <label key={f.key} class="ct-field-inline">
              <span>{f.label}</span>
              <select
                value={value[f.key]}
                disabled={disabled}
                onChange={(e) => onChange({ ...value, preset: null, [f.key]: (e.currentTarget as HTMLSelectElement).value } as Cosmetics)}
              >
                {f.options.map((o) => (
                  <option key={o} value={o}>
                    {cap(o)}
                  </option>
                ))}
              </select>
            </label>
          ))}
        </div>
        {preset && <p class="muted ct-small ct-advanced-note">Changing any of these replaces {preset.name} with your own villager.</p>}
      </details>
      )}
    </div>
  );
}

// OWNED BY cmu-eggs. The CMU easter eggs must never get in the way: placements stay off paths,
// doorsteps and buildings; every examine spot is reachable and away from door prompts; wandering
// creatures keep to walkable ground and off doorsteps; behaviour is a pure function of the clock
// and the public phase (no game state, no other entities). See docs/easter-eggs.md.
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PNG } from 'pngjs';
import { describe, expect, it } from 'vitest';
import { isBlockedPx, isBlockedTile, locationAt, tileCenterPx } from '@ct/protocol';
import { PROP_DEFS, townLayout as L, townMap } from '../src/index.js';
import * as E from '../src/eggs/index.js';
import { bfs, lattice } from './navsim.js';

const here = dirname(fileURLToPath(import.meta.url));
const TS = L.tileSize;
const lat = lattice(L);
const reach = bfs(lat, tileCenterPx(L, L.playerSpawn));
const reachable = (x: number, y: number) => {
  // nearest lattice node
  const p = { x: Math.round(x / 2) * 2, y: Math.round(y / 2) * 2 };
  return !lat.blocked[lat.node(p)] && reach[lat.node(p)] !== -1;
};
const doors = L.buildings.flatMap((b) => [tileCenterPx(L, b.door), tileCenterPx(L, b.interiorDoor)]);
const PATHS = new Set(['=', ':', 'o', 'O', 'b', 'g', 'D']);

describe('egg placements', () => {
  const all = [...E.EGG_STRUCTURES, ...E.EGG_PROPS];

  it('egg kinds are namespaced, merged into PROP_DEFS and placed in town.json data', () => {
    for (const k of Object.keys(E.EGG_PROP_DEFS)) {
      expect(k.startsWith('egg_')).toBe(true);
      expect(PROP_DEFS[k]).toBe(E.EGG_PROP_DEFS[k]);
    }
    for (const e of all) expect(townMap.objects.some((o) => o.kind === e.kind && o.x === e.x && o.y === e.y)).toBe(true);
  });

  it('collision footprints sit on open ground: no roads, paths, buildings, doorsteps or other props', () => {
    const others = townMap.objects.filter((o) => o.kind !== 'building' && !o.kind.startsWith('egg_') && PROP_DEFS[o.kind]?.col);
    const otherCol = new Set<string>();
    for (const o of others) {
      const c = PROP_DEFS[o.kind]!.col!;
      for (let j = 0; j < c.h; j++) for (let i = 0; i < c.w; i++) otherCol.add(`${o.x + c.x + i},${o.y + c.y + j}`);
    }
    for (const e of all) {
      const c = E.EGG_PROP_DEFS[e.kind]!.col;
      if (!c) continue;
      for (let j = 0; j < c.h; j++)
        for (let i = 0; i < c.w; i++) {
          const x = e.x + c.x + i;
          const y = e.y + c.y + j;
          const g = townMap.ground[y]![x]!;
          expect(PATHS.has(g), `${e.kind} on path tile ${x},${y} (${g})`).toBe(false);
          expect(otherCol.has(`${x},${y}`), `${e.kind} overlaps a prop at ${x},${y}`).toBe(false);
          for (const b of L.buildings) {
            const f = b.footprint;
            expect(x >= f.x && x < f.x + f.w && y >= f.y && y < f.y + f.h, `${e.kind} inside ${b.id}`).toBe(false);
            for (const d of [b.door, b.interiorDoor]) expect(Math.abs(d.x - x) <= 1 && Math.abs(d.y - y) <= 1, `${e.kind} next to ${b.id} door`).toBe(false);
          }
        }
    }
  });

  it('every egg stays outdoors and well away from the square, where the town talks', () => {
    for (const e of all) {
      expect(locationAt(L, e.x * TS + 8, e.y * TS + 8), e.kind).toBe('outdoors');
      const d = Math.hypot(e.x * TS + 8 - L.square.cx, e.y * TS + 8 - L.square.cy);
      expect(d, `${e.kind} too close to the square`).toBeGreaterThan(L.square.r + 3 * TS);
    }
    for (const h of E.EGG_HOTSPOTS) expect(Math.hypot(h.x - L.square.cx, h.y - L.square.cy), h.id).toBeGreaterThan(L.square.r + 3 * TS);
  });

  it('every egg sprite exists at the exact size of its kind (when generated)', () => {
    const dir = join(here, '..', 'src', 'eggs');
    for (const [frame, rel] of Object.entries(E.EGG_SPRITES)) {
      const p = join(dir, rel);
      if (!existsSync(p)) continue; // generated by eggs/scripts/build.ts
      const png = PNG.sync.read(readFileSync(p));
      const def = E.EGG_PROP_DEFS[frame];
      if (def) expect([png.width, png.height], frame).toEqual([def.w, def.h]);
      // transparent background: the corners are empty
      expect(png.data[3], `${frame} top-left alpha`).toBe(0);
    }
    const gen = join(here, '..', 'generated', 'eggs');
    if (existsSync(gen)) for (const f of E.EGG_FRAMES) expect(readdirSync(gen)).toContain(`${f}.png`);
    // the 2x art-density set: exactly twice the 1x frame
    const gen2 = join(gen, '2x');
    if (existsSync(gen2))
      for (const f of E.EGG_FRAMES) {
        const one = PNG.sync.read(readFileSync(join(gen, `${f}.png`)));
        const two = PNG.sync.read(readFileSync(join(gen2, `${f}.png`)));
        expect([two.width, two.height], f).toEqual([one.width * 2, one.height * 2]);
      }
  });
});

describe('examine spots', () => {
  it('are reachable, in the right place, and well away from every door prompt', () => {
    for (const h of E.EGG_HOTSPOTS) {
      expect(locationAt(L, h.x, h.y), h.id).toBe(h.location);
      expect(isBlockedPx(L, h.x, h.y), `${h.id} stand point blocked`).toBe(false);
      if (h.location === 'outdoors') expect(reachable(h.x, h.y), `${h.id} reachable`).toBe(true);
      for (const d of doors) expect(Math.hypot(d.x - h.x, d.y - h.y), `${h.id} near a door`).toBeGreaterThan(h.r + 22);
    }
  });

  it('do not overlap each other', () => {
    const H = E.EGG_HOTSPOTS;
    for (let i = 0; i < H.length; i++)
      for (let j = i + 1; j < H.length; j++) if (H[i]!.location === H[j]!.location) expect(Math.hypot(H[i]!.x - H[j]!.x, H[i]!.y - H[j]!.y), `${H[i]!.id}/${H[j]!.id}`).toBeGreaterThan(H[i]!.r + H[j]!.r - 8);
  });

  it('interior spots are reachable from their room door', () => {
    for (const h of E.EGG_HOTSPOTS.filter((x) => x.location !== 'outdoors')) {
      const b = L.buildings.find((x) => `bld:${x.id}` === h.location)!;
      const prev = bfs(lat, tileCenterPx(L, b.interiorDoor));
      const p = { x: Math.round(h.x / 2) * 2, y: Math.round(h.y / 2) * 2 };
      expect(prev[lat.node(p)], h.id).not.toBe(-1);
    }
  });
});

describe('creatures (course mascots, Scotty, the buggy, the ghost queue)', () => {
  const avoid = E.doorAvoidSet(L);

  it('wander only on walkable, reachable ground and never on a doorstep', () => {
    for (const w of E.WANDERERS) {
      const r = E.planLoop(L, w.waypoints);
      expect(r.total, w.id).toBeGreaterThan(64);
      for (let d = 0; d <= r.total; d += 2) {
        const p = E.poseAt(r, d / w.speed, w.speed, 1, 0);
        const tx = Math.floor(p.x / TS);
        const ty = Math.floor(p.y / TS);
        expect(isBlockedTile(L, tx, ty), `${w.id} at ${tx},${ty}`).toBe(false);
        expect(Math.hypot(p.x - L.square.cx, p.y - L.square.cy), `${w.id} in the square`).toBeGreaterThan(L.square.r + TS);
        expect(avoid.has(`${tx},${ty}`), `${w.id} on a doorstep ${tx},${ty}`).toBe(false);
        expect(locationAt(L, p.x, p.y)).toBe('outdoors');
      }
      expect(reachable(r.pts[0]!.x, r.pts[0]!.y), `${w.id} area reachable`).toBe(true);
    }
  });

  it('Requin stays in the pond and the frogs stay on its shore', () => {
    for (let t = 0; t < 600; t += 1.3) {
      const s = E.requinAt(t);
      expect(townMap.ground[Math.floor(s.y / TS)]![Math.floor(s.x / TS)], `fin at t=${t}`).toBe('~');
      for (const lag of [0, 2]) {
        const f = E.frogAt(t, lag);
        expect(townMap.ground[Math.floor((f.y + (f.hopping ? 4 : 0)) / TS)]![Math.floor(f.x / TS)], `frog at t=${t}`).not.toBe('~');
      }
    }
  });

  it('Polly perches on lamps; the ghost queue stands on open ground at the crypt', () => {
    for (const p of E.POLLY.perches) {
      const tx = Math.floor(p.x / TS);
      const lampY = Math.round((p.y + 46) / TS) - 1;
      expect(townMap.objects.some((o) => o.kind === 'lamp' && o.x === tx && o.y === lampY), `lamp at ${tx},${lampY}`).toBe(true);
    }
    for (const g of E.GHOST_QUEUE) {
      expect(isBlockedPx(L, g.x, g.y)).toBe(false);
      expect(avoid.has(`${Math.floor(g.x / TS)},${Math.floor(g.y / TS)}`)).toBe(false);
    }
    expect(townMap.objects.some((o) => o.kind === 'crypt')).toBe(true);
  });

  it('Opal swims in the river, Cilantro waits outside the gate, the fox and red panda sit on the bank, Greenting lives in the well', () => {
    const path = E.riverPath(townMap.ground);
    expect(path.length).toBeGreaterThan(8);
    for (let t = 0; t < 2000; t += 3.7) {
      const p = E.opalAt(path, t);
      expect(['~', 'b']).toContain(townMap.ground[Math.floor(p.y / TS)]![Math.floor(p.x / TS)]);
    }
    const ground = (p: { x: number; y: number }) => townMap.ground[Math.floor((p.y - 1) / TS)]![Math.floor(p.x / TS)]!;
    for (const p of [E.CILANTRO, E.MINCUT_MAXFLOW.fox, E.MINCUT_MAXFLOW.panda]) {
      expect(['~', ' ', 'T', 'w', 'h']).not.toContain(ground(p));
      expect(locationAt(L, p.x, p.y - 1)).toBe('outdoors');
      for (const d of doors) expect(Math.hypot(d.x - p.x, d.y - p.y)).toBeGreaterThan(40);
    }
    expect(E.CILANTRO.y).toBeGreaterThan(90 * TS); // outside the town wall
    const well = townMap.objects.find((o) => o.kind === 'well')!;
    expect(Math.abs(E.GREENTING.x - (well.x * TS + 16))).toBeLessThanOrEqual(4);
    expect(E.greentingRise(1)).toBeGreaterThan(0);
    expect(E.greentingRise(20)).toBe(0);
  });

  it('the Randy Pausch bridge lanterns line the south-lane footbridge', () => {
    const l = E.bridgeLanterns(L, townMap.ground);
    expect(l.length).toBeGreaterThanOrEqual(8);
    for (const p of l) expect(Math.abs(p.y - 67 * TS)).toBeLessThanOrEqual(TS + 1);
  });
});

describe('privacy and determinism', () => {
  it('depends only on the clock and the public phase', () => {
    expect(E.eggDark('night', 12)).toBe(true);
    expect(E.eggDark('bedtime', 12)).toBe(true);
    expect(E.eggDark('dawn', 12)).toBe(true);
    expect(E.eggDark('day', 2)).toBe(false); // in-game day stays day whatever the clock says
    expect(E.eggDark('waiting', 23)).toBe(true); // in the lobby the wall clock decides
    expect(E.eggDark('waiting', 14)).toBe(false);
    const t = 1_790_000_123.4;
    expect(E.pollyAt(t)).toEqual(E.pollyAt(t));
    expect(E.fencePaint(123, 13)).toEqual(E.fencePaint(123, 13));
    expect(E.fencePaint(123, 13).message).toBeLessThan(13);
  });

  it('egg code never touches the network, other entities or game state', () => {
    const root = join(here, '..', '..', '..');
    const files = [join(here, '..', 'src', 'eggs', 'world.ts'), join(here, '..', 'src', 'eggs', 'index.ts')];
    const client = join(root, 'apps', 'client', 'src', 'game', 'eggs');
    if (existsSync(client)) for (const f of readdirSync(client)) if (f.endsWith('.ts')) files.push(join(client, f));
    for (const f of files) {
      const src = readFileSync(f, 'utf8').replace(/\/\/.*$/gm, '').replace(/\/\*[\s\S]*?\*\//g, '');
      for (const bad of ['remoteEntities', '.send(', 'gameView', 'lobbyView', 'innerHTML', 'storytellerVisiting', 'world:snapshot', 'fetch(', 'WebSocket'])
        expect(src.includes(bad), `${f} uses ${bad}`).toBe(false);
    }
    // ../layout.ts imports eggs/index.ts while initialising: no value imports back into layout
    const idx = readFileSync(join(here, '..', 'src', 'eggs', 'index.ts'), 'utf8');
    expect(/import\s+\{[^}]*\}\s+from\s+'\.\.\/layout\.js'/.test(idx.replace(/import type/g, ''))).toBe(false);
  });
});

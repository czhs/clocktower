// High-density bitmap faces for UI density D = 2 (owner: UI lead; docs/UI.md §2.4 + "Density"). Pure data, no imports
// (kit.js imports this file; a group module never needs it directly: drawText({density: 2}) / a density view picks it).
//
// Contract (what makes a D=2 face drop-in): every glyph's ADVANCE is exactly 2x its 1x glyph's advance, and the
// vertical metrics are exactly 2x (cap, x-height, descender, line advance, space, tracking). So textWidth(s, f, 2) ===
// 2 * textWidth(s, f) for every string: a layout computed at 1x (box sizes, wrap points, centring) is pixel-identical at
// D=2, only the glyphs get twice the detail. A glyph drawing may be narrower than its advance (it is left-aligned in its
// cell, or offset by `dx`); kit.js checks the advances at registration and warns on a mismatch.
//
// Style (both faces): 2-px vertical stems, 1-px horizontals (a quiet thick/thin contrast that keeps the 1x faces' weight
// but reads finer), curves cut by 1-px steps, real descenders (4 rows), lowercase with a single-storey a / g like the 1x
// body face, 1-px terminal hooks on j / l / t / y. Glyph format = kit G('rows', top): rows top-down, '#' = ink, top =
// first row (row 0 = cap top). body2: cap 12, x-height 8 (top 4), descender 4 (rows 12..15). tiny2: cap 10, caps only.
// The display face at D=2 is derived from the hud group's DISPLAY (kit.js derive2x: Scale2x-smoothed, see there).

function G(rows, top = 0, dx = 0) { return { rows: rows.split('/'), top, dx }; }


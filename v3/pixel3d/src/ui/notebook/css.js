// DOM skin proposal for the v2 notebook's free-text page (owner: notebook group; docs/UI.md row 41b, §5). Builds
// out/ui/notebook.css (the bake module files() output, tools/uibake.sh notebook): the real <textarea class="ctn-text">
// stays a native textarea (IME, screen readers, undo, spellcheck off as in v2) and only adopts the page art:
//   - border-image = the lined page plate (binding holes + rose margin in the left inset, no `fill`)
//   - background  = parchment + the rule tile, background-attachment: local (the rules SCROLL with the text)
//   - line-height = the rule pitch x --px, so every DOM line sits on a rule; caret / selection / placeholder / scrollbar
//     in the page tokens
//   - page tabs: role="tablist" with two role="tab" buttons (Seats | Notes) using the baked tab plates of panels.css
//     and the 9x9 tab glyphs here.
//   - r6 height snap: the border-image left edge carries the binding holes (period 10 texels = the 9-slice middle). The textarea's
//     border-box height is snapped to 8 + 10 n texels (--ctn-rows = n, default 14), so the middle of the 9-slice is a
//     whole number of hole periods and no hole is ever clipped ('repeat' centres its tiles). Vertical 'space' as a
//     second guard (a non-snapped height leaves even gaps, never half holes). The holes are FIXED to the page frame;
//     only the rules and the text scroll.
//   - r6 pixel face (opt-in): .ctn.ctn-pixelfont types in 'CT Pixel Body', a TTF built from the kit body bitmap font
//     (ttf.js), 8px x --px = one glyph pixel per --px; characters it lacks fall back to the v2 vector font per glyph.
// Browser only (toDataURL). Integer --px only (2 at 720p, 3 at 1080p), drop in AFTER theme.css + panels.css.
import { toCanvas, hex } from '../kit.js';
import { pageFrames, pageMats, PAGE } from './art.js';
import { ttfBase64 } from './ttf.js';

const uri = (im) => toCanvas(im).toDataURL('image/png');

export function buildCss(T) {
  const F = Object.fromEntries(pageFrames(T)), C = pageMats(T), I = PAGE.ins;
  const px = (n) => `calc(${n}px * var(--px))`;
  const L = [];
  const rule = (sel, body) => L.push(`${sel} { ${body} }`);
  L.push('/* pixel3d notebook page skin for Clocktower v2 (generated by tools/uibake.sh notebook; do not edit).',
    '   Integer --px only. The textarea stays native; text keeps the DOM font (or the opt-in pixel face, .ctn-pixelfont),',
    '   sized so one line = one rule. Height = 8 + 10 x --ctn-rows texels: never set a free height on .ctn-text (holes clip);',
    '   to fill a flexible box, round it in JS: rows = floor((cssHeight / px - 8) / 10). */');
  L.push(`@font-face { font-family: 'CT Pixel Body'; src: url(data:font/ttf;base64,${ttfBase64()}) format('truetype'); font-display: block; }`);
  rule('.ctn', '--px: 2;');
  rule('.ctn.ctp-px3', '--px: 3;');
  // page tabs (new): <div class="ctn-tabs" role="tablist"><button role="tab" aria-selected="true" class="ctn-tab ctn-tab-seats">…
  rule('.ctn-tabs', `display: flex; gap: ${px(1)}; align-items: flex-end; margin-left: auto;`);
  rule('.ctn-tab', `width: ${px(14)}; height: ${px(12)}; min-height: 0; padding: 0; display: flex; align-items: center; justify-content: center; font-size: 0;`);
  rule('.ctn-tab[aria-selected=\'true\']', `height: ${px(13)};`);
  for (const n of ['seats', 'notes']) {
    rule(`.ctn-tab-${n}::before`, `content: ''; width: ${px(9)}; height: ${px(9)}; background: url(${uri(F[`tab-glyph-${n}`])}) 0 0 / 100% 100%; image-rendering: pixelated;`);
    rule(`.ctn-tab-${n}[aria-selected='true']::before`, `background-image: url(${uri(F[`tab-glyph-${n}-on`])});`);
  }
  // the page
  rule('.ctn-text', [
    `border-style: solid; border-color: transparent; border-width: ${px(I.t)} ${px(I.r)} ${px(I.b)} ${px(I.l)};`,
    `border-image: url(${uri(F['notes-page'])}) ${I.t} ${I.r} ${I.b} ${I.l} / ${px(I.t)} ${px(I.r)} ${px(I.b)} ${px(I.l)} / 0 repeat space;`,
    // snapped height (border box = t + b + 10 n texels): whole hole periods on the left edge
    `box-sizing: border-box; --ctn-rows: 14; height: calc((${I.t + I.b}px + ${PAGE.pitch}px * var(--ctn-rows)) * var(--px)); min-height: 0;`,
    // rule tile = one line box (pitch rows, rule on row pitch-2 = under the descenders), tiled from the first line's top
    `background: ${hex(C.fill)} url(${uri(F['notes-rule'])}) 0 ${px(1)} / ${px(8)} ${px(PAGE.pitch)} repeat;`,
    'background-attachment: local; background-clip: padding-box; border-radius: 0; image-rendering: pixelated;',
    `padding: ${px(1)} ${px(1)} 0 ${px(PAGE.textX - I.l)};`,
    `line-height: ${px(PAGE.pitch)}; font-size: ${px(7)}; color: ${hex(C.ink)}; caret-color: ${hex(C.ink)};`,
    // no free resize: a dragged height breaks the hole period (set --ctn-rows instead, or round in a ResizeObserver)
    'resize: none; outline: none; box-shadow: none;',
  ].join(' '));
  // opt-in pixel face: the game's body font in the native textarea (IME / missing glyphs fall back to the vector font)
  rule('.ctn.ctn-pixelfont .ctn-text', `font-family: 'CT Pixel Body', var(--font, 'Alegreya Sans'), system-ui, sans-serif; font-size: ${px(8)}; -webkit-font-smoothing: none; font-smooth: never; font-kerning: none; font-variant-ligatures: none;`);
  rule('.ctn-text:focus', 'border-color: transparent; outline: none;');
  rule('.ctn-text::selection', `background: ${hex(C.sel)}; color: ${hex(C.ink)};`);
  rule('.ctn-text::placeholder', `color: ${hex(C.hint)}; opacity: 1;`);
  rule('.ctn-text', `scrollbar-width: thin; scrollbar-color: ${hex(C.thumb)} ${hex(C.track)};`);
  rule('.ctn-text::-webkit-scrollbar', `width: ${px(3)};`);
  rule('.ctn-text::-webkit-scrollbar-track', `background: ${hex(C.track)};`);
  rule('.ctn-text::-webkit-scrollbar-thumb', `border-style: solid; border-width: ${px(2)} 0; border-image: url(${uri(F['notes-scroll-thumb'])}) 2 0 fill / ${px(2)} 0 / 0 repeat; image-rendering: pixelated;`);
  // (status text stays in the ink header: v2 .ctn-status-* colours already read there)
  rule('.ctn-page-label', 'display: none; /* the Notes tab names the page */');
  return L.join('\n') + '\n';
}

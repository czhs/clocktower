// CSS skin export (owner: panels group; docs/UI.md §2.2 tier CSS, §5 "DOM skin"). Builds out/ui/panels.css: border-image
// 9-slices, control images, glyph classes and cursors for the v2 DOM (apps/client/src/ui/**), at an integer scale --px.
// Every image is an inline data: URI (border-image cannot crop an atlas sub-rect), so panels.css is self-contained.
// Browser only (toDataURL). Selectors mirror the v2 ones (theme.css / lobby.css / Settings.css / notebook.css) plus
// opt-in .ctp-* classes; drop it in AFTER theme.css.
import { toCanvas, PixelImage } from '../kit.js';
import { CURSORS } from './art.js';

const uri = (im) => toCanvas(im).toDataURL('image/png');
const scaled = (im, s) => { const o = new PixelImage(im.w * s, im.h * s); o.blit(im, 0, 0, { scale: s }); return o; };

export function buildCss(K) {
  const { img, insets } = K;
  const px = (n) => `calc(${n}px * var(--px))`;
  const nine = (name, extra = '') => {
    const i = insets[name];
    return `border-style: solid; border-color: transparent; border-width: ${px(i.t)} ${px(i.r)} ${px(i.b)} ${px(i.l)}; ` +
      `border-image: url(${uri(img[name])}) ${i.t} ${i.r} ${i.b} ${i.l} fill / ${px(i.t)} ${px(i.r)} ${px(i.b)} ${px(i.l)} / 0 repeat; ` +
      `background: none; border-radius: 0; image-rendering: pixelated;${extra}`;
  };
  const pic = (name, w = img[name].w, h = img[name].h) => `width: ${px(w)}; height: ${px(h)}; background: url(${uri(img[name])}) 0 0 / 100% 100% no-repeat; image-rendering: pixelated;`;
  const L = [];
  const rule = (sel, body) => L.push(`${sel} { ${body} }`);
  L.push('/* pixel3d panel skin for Clocktower v2 (generated by tools/uibake.sh panels; do not edit). Integer scale only:',
    '   set --px to the UI scale (2 at 720p, 3 at 1080p). Text stays the DOM font; frames, controls, glyphs and cursors',
    '   are texel-exact pixel art. Frame names = out/ui/panels.json frames; insets = meta.nineSlice. */');
  rule(':root', '--px: 2;');
  rule('.ctp-px3', '--px: 3;');
  // panels
  rule('.panel, .ct-art-panel, .ct-chat, .ct-help, .ctp-panel', nine('panel'));
  rule('.ct-modal, .ctp-modal', nine('modal'));
  rule('.ct-art-parchment, .cty-pamphlet, .ctp-parchment', nine('panel-parchment', ' color: var(--ink);'));
  rule('.ct-modal-backdrop, .ctp-scrim', `background: url(${uri(img.scrim)}) 0 0 / ${px(4)} ${px(4)};`);
  // buttons (the v2 skinned screens: same scope list as theme.css, + .ctp-skin)
  const scope = ':is(.ct-auth, .ct-home, .ct-waiting, .ct-modal, .ct-help-foot, .ct-chat-form, .screen.center, .ct-toolbar, .ct-admin, .ct-art-buttons, .ctp-skin)';
  const B = `${scope} button:not(.ct-link, .ct-preset, .ct-waiting-toggle, .ct-chat-min, .ct-help-close, .ct-waiting-newbie, [role='tab'], [role='radio'], .ct-danger-btn, .ct-switch, .ctp-switch)`;
  rule(B, nine('button', ' color: var(--text);'));
  rule(`${B}:hover:not(:disabled)`, nine('button-hover'));
  rule(`${B}:active:not(:disabled)`, nine('button-pressed', ' transform: none;'));
  rule(`${B}[aria-pressed='true']`, nine('button-selected', ' filter: none;'));
  rule(`${B}:disabled`, nine('button-disabled', ' filter: none; color: var(--muted);'));
  rule(`${B}.primary`, nine('button-primary', ' color: #F7E0A0;'));
  rule(`${B}.primary:hover:not(:disabled)`, nine('button-primary-hover'));
  rule(`${B}.primary:active:not(:disabled)`, nine('button-primary-pressed'));
  rule(`${B}.primary:disabled`, nine('button-primary-disabled', ' color: #A57B36;'));
  rule(`${scope} button.ct-danger-btn`, nine('button-danger'));
  rule(`${scope} button.ct-danger-btn:hover:not(:disabled)`, nine('button-danger-hover'));
  // segmented controls + tabs
  rule(".ct-seg button, .ct-seg [role='radio']", nine('segment'));
  rule(".ct-seg [aria-checked='true'], .ct-seg [aria-pressed='true']", nine('segment-on', ' color: #F7E0A0;'));
  rule("[role='tab']", nine('tab'));
  rule("[role='tab']:hover:not([aria-selected='true'])", nine('tab-hover'));
  rule("[role='tab'][aria-selected='true']", nine('tab-active', ' color: var(--accent);'));
  rule("[role='tablist']", `border-bottom: ${px(2)} solid transparent; border-image: url(${uri(img['tab-strip'])}) 0 0 2 0 / 0 0 ${px(2)} 0 repeat;`);
  // inputs
  rule("input:not([type='checkbox'], [type='radio'], [type='range']), textarea", nine('input'));
  rule("input:not([type='checkbox'], [type='radio'], [type='range']):hover:not(:disabled), textarea:hover:not(:disabled)", nine('input-hover'));
  rule("input:not([type='checkbox'], [type='radio'], [type='range']):focus-visible, textarea:focus-visible", nine('input-focus', ' outline: none;'));
  rule("input:disabled, textarea:disabled", nine('input-disabled'));
  // select: the chevron cannot live in a repeating slice (it tiled 3x on a tall select): frame without fill + inkSunk
  // background colour + the chevron as a positioned background image
  { const i = insets.input;
    rule('select:not([multiple])', `border-style: solid; border-color: transparent; border-width: ${px(i.t)} ${px(i.r)} ${px(i.b)} ${px(i.l)}; ` +
      `border-image: url(${uri(img.input)}) ${i.t} ${i.r} ${i.b} ${i.l} / ${px(i.t)} ${px(i.r)} ${px(i.b)} ${px(i.l)} / 0 repeat; border-radius: 0; ` +
      `background: ${K.T.inkSunk} url(${uri(img['select-chevron'])}) no-repeat right ${px(3)} center / ${px(img['select-chevron'].w)} ${px(img['select-chevron'].h)}; ` +
      `padding-right: ${px(12)}; image-rendering: pixelated; appearance: none; -webkit-appearance: none; -moz-appearance: none;`); }
  // (r1: without appearance none Chromium painted its own anti-aliased arrow over the baked chevron)
  rule(':focus-visible', `outline: none; box-shadow: 0 0 0 ${px(1)} var(--accent), 0 0 0 ${px(2)} #5E4220;`);
  // checkbox / radio
  rule("input[type='checkbox']", `appearance: none; -webkit-appearance: none; border: 0; border-image: none; margin: 0; padding: 0; ${pic('checkbox')}`);
  rule("input[type='checkbox']:hover:not(:disabled)", `background-image: url(${uri(img['checkbox-hover'])});`);
  rule("input[type='checkbox']:checked", `background-image: url(${uri(img['checkbox-on'])});`);
  rule("input[type='checkbox']:indeterminate", `background-image: url(${uri(img['checkbox-mixed'])});`);
  rule("input[type='checkbox']:disabled", `background-image: url(${uri(img['checkbox-disabled'])});`);
  rule("input[type='radio']", `appearance: none; -webkit-appearance: none; border: 0; border-image: none; margin: 0; padding: 0; ${pic('radio')}`);
  rule("input[type='radio']:hover:not(:disabled)", `background-image: url(${uri(img['radio-hover'])});`);
  rule("input[type='radio']:checked", `background-image: url(${uri(img['radio-on'])});`);
  // switch (v2 .ct-switch is a button with a knob span; the skin draws the whole switch, knob span hidden)
  rule('button.ct-switch, .ct-switch, .ctp-switch', `border: 0; border-image: none; padding: 0; min-height: 0; ${pic('switch')}`);
  rule('.ct-switch .ct-switch-knob', 'display: none;');
  rule('button.ct-switch.on, .ct-switch.on, .ctp-switch.on', `background-image: url(${uri(img['switch-on'])});`);
  rule('.ct-switch.ctp-anim, .ctp-switch.ctp-anim', 'animation: ctp-switch-on calc(4s / 30) steps(1) both;');
  L.push(`@keyframes ctp-switch-on { 0% { background-image: url(${uri(img.switch_1)}); } 50% { background-image: url(${uri(img.switch_2)}); } 100% { background-image: url(${uri(img.switch_3)}); } }`);
  // range slider (Chromium + Firefox)
  rule("input[type='range']", `appearance: none; -webkit-appearance: none; background: none; height: ${px(12)}; border: 0;`);
  for (const [track, thumb] of [['::-webkit-slider-runnable-track', '::-webkit-slider-thumb'], ['::-moz-range-track', '::-moz-range-thumb']]) {
    rule(`input[type='range']${track}`, `height: ${px(5)}; ${nine('slider-track')}`);
    rule(`input[type='range']${thumb}`, `appearance: none; -webkit-appearance: none; border: 0; border-radius: 0; margin-top: ${px(-4)}; ${pic('slider-knob')}`);
    rule(`input[type='range']:active${thumb}`, `background-image: url(${uri(img['slider-knob-pressed'])});`);
  }
  rule("input[type='range']::-moz-range-progress", `height: ${px(5)}; ${nine('slider-fill')}`);
  // scrollbars
  rule('::-webkit-scrollbar', `width: ${px(6)}; height: ${px(6)};`);
  rule('::-webkit-scrollbar-track', nine('scrollbar-track'));
  rule('::-webkit-scrollbar-thumb', nine('scrollbar-thumb'));
  rule('::-webkit-scrollbar-thumb:hover', nine('scrollbar-thumb-hover'));
  // rows, chips, badges, tooltips, dividers
  rule('.ct-member, .ctn-seat, .ctp-row', nine('row'));
  rule('.ct-member:hover, .ctn-seat:hover, .ctp-row:hover', nine('row-hover'));
  rule('.ctp-row.selected, .ctn-seat.selected', nine('row-selected'));
  rule('.ct-member-away, .ctp-row.dead', nine('row-dead'));
  rule('.ct-badge', nine('chip', ' font-variant: small-caps;'));
  rule('.ct-badge-host', nine('chip-gold'));
  rule('.ct-badge-ready, .ctn-status-saved', nine('chip-ok'));
  rule('.ct-badge-st', nine('chip-violet'));
  rule('.ct-badge-away', nine('chip-dim'));
  rule('.ctp-tooltip, [role=tooltip]', nine('tooltip'));
  rule('.ct-chat-unread, .ctp-unread', nine('badge-unread', ` color: ${K.T.parchmentHi}; border-radius: 0; background: none;`));
  rule('.ct-chat-dot, .ctp-count', nine('badge-count', ` color: ${K.T.parchmentHi}; border-radius: 0; background: none;`));
  rule('.ct-waiting-newbie, .ctp-tip', nine('tip-strip'));
  rule('.ctp-well', nine('well'));
  rule('.ctp-avatar-well, .ctn-portrait', nine('avatar-well'));
  rule('hr, .ctp-divider', `border: 0; height: ${px(2)}; background: url(${uri(img['divider-iron'])}) 0 0 / ${px(4)} ${px(2)} repeat-x;`);
  rule('.ctp-divider-v2', `border-style: solid; border-color: transparent; border-width: 0 ${px(8)}; height: ${px(8)}; border-image: url(${uri(img.divider)}) 0 8 fill / 0 ${px(8)} / 0 repeat;`);
  rule('kbd, .ctp-kbd', nine('kbd'));
  rule('.ctp-spinner, .ct-spinner', `border: 0; border-radius: 0; animation: ctp-spin 0.9s steps(1) infinite; ${pic('spinner_0')}`);
  L.push(`@keyframes ctp-spin { ${[...Array(9)].map((_, k) => `${((k / 9) * 100).toFixed(3)}% { background-image: url(${uri(img['spinner_' + k])}); }`).join(' ')} }`);
  // glyphs + v2 icons (.ct-icon keeps the v2 16x16 box)
  for (const n of Object.keys(img).filter((n) => n.startsWith('glyph_'))) rule(`.ctp-${n.replace('_', '-')}`, `display: inline-block; vertical-align: middle; ${pic(n)}`);
  // cursors: CSS cursor images cannot scale with --px, so they ship pre-scaled (x2 default, x3 under .ctp-px3)
  for (const [n, c] of Object.entries(CURSORS)) {
    const css = n.replace('cursor-', '');
    const sel = { arrow: 'html, body', pointer: "button, a, [role='tab'], select, label", text: "input:not([type='checkbox'], [type='radio'], [type='range']), textarea", 'not-allowed': ':disabled' }[css];
    const val = (s) => `url(${uri(scaled(img[n], s))}) ${c.hot[0] * s} ${c.hot[1] * s}, ${css === 'arrow' ? 'default' : css === 'pointer-down' ? 'pointer' : css}`;
    rule(`.ctp-cursor-${css}${sel ? ', ' + sel : ''}`, `cursor: ${val(2)};`);
    rule(`.ctp-px3 .ctp-cursor-${css}${sel ? ', ' + sel.split(', ').map((s) => '.ctp-px3 ' + s).join(', ') : ''}`, `cursor: ${val(3)};`);
  }
  rule(':is(button, [role=tab]):active:not(:disabled)', `cursor: url(${uri(scaled(img['cursor-pointer-down'], 2))}) ${CURSORS['cursor-pointer-down'].hot[0] * 2} ${CURSORS['cursor-pointer-down'].hot[1] * 2}, pointer;`);
  rule('@media (prefers-reduced-motion: reduce) { .ctp-spinner, .ct-spinner', 'animation: none; } }');
  return L.join('\n') + '\n';
}

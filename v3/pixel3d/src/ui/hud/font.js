/** Pixel italic (nod to v2's IM Fell italic ability text): shear a rendered line 1 px right per 3 rows above the baseline. */
export function italicize(img, capTop, cap = 6) {
  const out = img.clone().clear();
  const base = capTop + cap - 1;
  for (let y = 0; y < img.h; y++) {
    const s = Math.floor((base - y) / 3);
    for (let x = 0; x < img.w; x++) { const v = img.get(x, y); if (v[3]) out.set(x + s, y, v); }
  }
  return out;
}
